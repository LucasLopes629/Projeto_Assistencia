     private void adicionarMenuLogout() {
    javax.swing.JMenu jMenuLogout = new javax.swing.JMenu("Logout");
    jMenuBar1.add(jMenuLogout);
    jMenuBar1.revalidate();

    jMenuLogout.addMouseListener(new java.awt.event.MouseAdapter() {
        @Override
        public void mouseClicked(java.awt.event.MouseEvent evt) {
            int opc = javax.swing.JOptionPane.showConfirmDialog(null, "Deseja realmente sair?");
            if (opc == javax.swing.JOptionPane.YES_OPTION) {
                logado = false;
                jTFUsuario.setEnabled(true);
                jTFSenha.setEnabled(true);
                jBTNEntrar.setEnabled(true);
                jTFUsuario.setText("");
                jTFSenha.setText("");
                jMenuSistema.setEnabled(false);
                jMenuItemEstoque.setEnabled(false);
                jMenuItem2.setEnabled(false);

              
                jMenuBar1.remove(jMenuLogout);
                jMenuBar1.revalidate();
                jMenuBar1.repaint();

                javax.swing.JOptionPane.showMessageDialog(null, "Você saiu do sistema!");
            }
        }
    });
}
