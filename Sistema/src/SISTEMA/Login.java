    private void jBTNEntrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBTNEntrarActionPerformed
        

    String login = jTFUsuario.getText();
    String senha = jTFSenha.getText();
    
    if (login.isEmpty() || senha.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Preencha todos os campos!");
        return;
    }

    java.sql.Connection conn = null;
    java.sql.PreparedStatement pst = null;
    java.sql.ResultSet rs = null;

    try {
        conn = Conexao.conecta();
        String sql = "SELECT * FROM funcionario WHERE Email = ? AND CPF = ?";
        pst = conn.prepareStatement(sql);
        pst.setString(1, login);
        pst.setString(2, senha);
        rs = pst.executeQuery();

        if (rs.next()) {
            logado = true;
            

            javax.swing.JOptionPane.showMessageDialog(this,
                "Login bem sucedido.\nBem vindo, " + login + "!");
            

            jTFUsuario.setEnabled(false);
            jTFSenha.setEnabled(false);
            jBTNEntrar.setEnabled(false);
            logado = true;
            jMenuSistema.setEnabled(true);
            jMenuItemEstoque.setEnabled(true);
            jMenuItem2.setEnabled(true);
            
            
          adicionarMenuLogout();
            
        } else {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Login ou senha incorretos!", "Erro", javax.swing.JOptionPane.ERROR_MESSAGE);
        }

    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Erro ao conectar: " + e.getMessage());
    } finally {
        try {
            if (rs != null) rs.close();
            if (pst != null) pst.close();
            if (conn != null) conn.close();
        } catch (Exception e) {}
    }
    }//GEN-LAST:event_jBTNEntrarActionPerformed

